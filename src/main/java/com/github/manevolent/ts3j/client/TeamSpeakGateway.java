    public synchronized void toggleAwayStatus() {
        ClientView local = requireLocalClient();
        queueClientFlagUpdate("client_away", !local.isAway());
    }

    public synchronized void setAwayStatus(boolean away) {
        requireLocalClient();
        queueClientFlagUpdate("client_away", away);
    }

    public synchronized void toggleMicrophoneMute() {
        ClientView local = requireLocalClient();
        queueClientFlagUpdate("client_input_muted", !local.isInputMuted());
    }

    public synchronized void setMicrophoneMuted(boolean muted) {
        requireLocalClient();
        if (audioBridge != null) audioBridge.setMuted(muted);
        queueClientFlagUpdate("client_input_muted", muted);
    }

    public synchronized void toggleAudioMute() {
        ClientView local = requireLocalClient();
        queueClientFlagUpdate("client_output_muted", !local.isOutputMuted());
    }

