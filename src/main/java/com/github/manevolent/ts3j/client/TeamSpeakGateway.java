    @Override
    public void onClientJoin(ClientJoinEvent event) {
        if (isDuplicate("join", event.getMap())) return;
        Client client = new Client(event.getMap());
        if (client.getType() != 0) {
            nonUserClientIds.add(client.getId());
            return;
        }
        int channelId = event.getClientTargetId() >= 0
                ? event.getClientTargetId() : client.getChannelId();
        ClientView view = toClient(client, channelId);
        boolean sync = initialSync;
        int previousCurrentChannel;
        boolean localClient;
        synchronized (this) {
            ClientView previous = clients.get(view.getId());
            // A move is represented by notifyclientmoved in ts3j. If a late
            // join notification arrives for a client already tracked in a
            // different channel, keep the newer local route until the next
            // authoritative listClients() reconciliation.
            if (previous != null && previous.getChannelId() != channelId) return;
            previousCurrentChannel = currentChannelId;
            localClient = view.getId() == localClientId();
            clients.put(view.getId(), view);
            if (localClient) currentChannelId = channelId;
        }
        if (channelId >= 0 && config != null) {
            sessions.join(config.serverId(), channelId, view.getId(), clock.instant(),
                    sync, gatewayEventId("join", event.getMap()), 0L);
        }
        if (!localClient && channelId >= 0 && !sync) {
            queuePeerSessionMarker(socket, view.getId(), channelId);
        }
        applyPendingSessionMarkers();
        applyPendingServerSessionMarkers();
        respondToPendingSessionMarkerRequests();
        if (!sync && channelId >= 0) {
            queueChannelSessionMarkerRequest(socket, channelId);
            if (localClient) scheduleChannelSessionMarkerRetries(socket, channelId);
            // If this instance already knows the session start, answer the
            // fresh join immediately as well as requesting it. This removes a
            // race where the rejoining client leaves before the request's
            // response is delivered.
            respondToChannelSessionMarkerRequest(channelId);
        }
        if (!sync && previousCurrentChannel >= 0 && !localClient
                && channelId == previousCurrentChannel) {
            emitActivity(new TeamSpeakActivity(TeamSpeakActivity.Type.CLIENT_JOINED_CURRENT_CHANNEL,
                    view.getNickname(), "", channelName(channelId), serverName()));
        }
        refreshStatus();
    }

    @Override
    public void onClientMoved(ClientMovedEvent event) {
        if (isDuplicate("move", event.getMap())) return;
        int clientId = event.getClientId();
        int target = event.getTargetChannelId();
        int from = mapInt(event.getMap(), "cfid", -1);
        boolean sync = initialSync;
        int previousCurrentChannel;
        boolean localClient;
        String nickname;
        synchronized (this) {
            ClientView previous = clients.get(clientId);
            if (nonUserClientIds.contains(clientId)
                    || (previous != null && !isRealClient(previous))
                    || mapInt(event.getMap(), "client_type", 0) != 0) {
                if (mapInt(event.getMap(), "client_type", 0) != 0) {
                    nonUserClientIds.add(clientId);
                }
                clients.remove(clientId);
                publish();
                return;
            }
            if (from < 0 && previous != null) from = previous.getChannelId();
            ClientView old = previous == null ? null : previous;
            previousCurrentChannel = currentChannelId;
            localClient = clientId == localClientId();
            nickname = old == null ? "Usuario " + clientId : old.getNickname();
            clients.put(clientId, new ClientView(clientId, target,
                    nickname,
                    old == null ? "" : old.getUniqueIdentifier(),
                    old == null ? 0 : old.getType(),
                    old != null && old.isInputMuted(), old != null && old.isOutputMuted(),
                    old != null && old.isAway()));
            if (localClient) currentChannelId = target;
        }
        if (config != null && target >= 0) {
            sessions.move(config.serverId(), from, target, clientId, clock.instant(),
                    sync, gatewayEventId("move", event.getMap()), 0L);
        }
        if (!localClient && target >= 0 && !sync) {
            queuePeerSessionMarker(socket, clientId, target);
        }
        applyPendingSessionMarkers();
        applyPendingServerSessionMarkers();
        respondToPendingSessionMarkerRequests();
        if (!sync && target >= 0) {
            queueChannelSessionMarkerRequest(socket, target);
            if (localClient) scheduleChannelSessionMarkerRetries(socket, target);
            respondToChannelSessionMarkerRequest(target);
        }
        if (!sync && !localClient && previousCurrentChannel >= 0) {
            if (target == previousCurrentChannel && from != previousCurrentChannel) {
                emitActivity(new TeamSpeakActivity(TeamSpeakActivity.Type.CLIENT_SWITCHED_TO_CURRENT_CHANNEL,
                        nickname, channelName(from), channelName(target), serverName()));
            } else if (from == previousCurrentChannel && target != previousCurrentChannel) {
                emitActivity(new TeamSpeakActivity(TeamSpeakActivity.Type.CLIENT_SWITCHED_FROM_CURRENT_CHANNEL,
                        nickname, channelName(from), channelName(target), serverName()));
            }
        } else if (!sync && localClient && target >= 0 && target != from) {
            emitActivity(new TeamSpeakActivity(TeamSpeakActivity.Type.YOU_SWITCHED_CHANNEL,
                    "", channelName(from), channelName(target), serverName()));
        }
        refreshStatus();
    }

    @Override
    public void onClientLeave(ClientLeaveEvent event) {
        if (isDuplicate("leave", event.getMap())) return;
        int clientId = event.getClientId();
        int from = event.getClientFromId();
        boolean sync = initialSync;
        int previousCurrentChannel;
        boolean localClient;
        String nickname;
        synchronized (this) {
            ClientView previous = clients.get(clientId);
            if (nonUserClientIds.remove(clientId)
                    || (previous != null && !isRealClient(previous))
                    || mapInt(event.getMap(), "client_type", 0) != 0) {
                clients.remove(clientId);
                publish();
                return;
            }
            clients.remove(clientId);
            if (from < 0 && previous != null) from = previous.getChannelId();
            previousCurrentChannel = currentChannelId;
            localClient = clientId == localClientId();
            nickname = previous == null ? "Usuario " + clientId : previous.getNickname();
            if (localClient) currentChannelId = -1;
        }
        if (config != null) {
            sessions.leave(config.serverId(), from, clientId, clock.instant(),
                    gatewayEventId("leave", event.getMap()), 0L);
            clearSessionMarkerNegotiationAfterLeave(config.serverId(), from, clientId);
        }
        if (!sync && !localClient && from >= 0 && from == previousCurrentChannel) {
            emitActivity(new TeamSpeakActivity(TeamSpeakActivity.Type.CLIENT_LEFT_CURRENT_CHANNEL,
                    nickname, channelName(from), "", serverName()));
        }
        if (!sync && from >= 0) {
            queueChannelSessionMarkerRequest(socket, from);
        }
        refreshStatus();
    }

    @Override
    public void onClientChanged(ClientUpdatedEvent event) {
        int clientId = event.getClientId();
        TeamSpeakActivity inputActivity = null;
        TeamSpeakActivity outputActivity = null;
        TeamSpeakActivity awayActivity = null;
        synchronized (this) {
            if (nonUserClientIds.contains(clientId)) return;
            ClientView previous = clients.get(clientId);
            if (previous != null && isRealClient(previous)) {
                Client raw = new Client(event.getMap());
                boolean inputMuted = hasClientFlag(event.getMap(), "client_input_muted", previous.isInputMuted());
                boolean outputMuted = hasClientFlag(event.getMap(), "client_output_muted", previous.isOutputMuted());
                boolean away = hasClientFlag(event.getMap(), "client_away", previous.isAway());
                boolean localClient = clientId == localClientId();
                clients.put(clientId, new ClientView(clientId, previous.getChannelId(),
                        raw.getNickname().isEmpty() ? previous.getNickname() : raw.getNickname(),
                        previous.getUniqueIdentifier(),
                        previous.getType(), inputMuted, outputMuted, away));
                if (!initialSync && localClient) {
                    if (previous.isInputMuted() != inputMuted
                            && event.getMap().containsKey("client_input_muted")) {
                        inputActivity = activityForClientFlag("client_input_muted", inputMuted);
                    }
                    if (previous.isOutputMuted() != outputMuted
                            && event.getMap().containsKey("client_output_muted")) {
                        outputActivity = activityForClientFlag("client_output_muted", outputMuted);
                    }
                    if (previous.isAway() != away && event.getMap().containsKey("client_away")) {
                        awayActivity = activityForClientFlag("client_away", away);
                    }
                }
            }
        }
        emitActivity(inputActivity);
        emitActivity(outputActivity);
        emitActivity(awayActivity);
        publish();
    }

