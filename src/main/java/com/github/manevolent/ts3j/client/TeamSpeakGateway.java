    private String gatewayEventId(String type, Map<String, String> map) {
        return eventSource + ":" + nextSequence() + ":" + eventSignature(type, map);
    }

    private boolean isDuplicate(String type, Map<String, String> map) {
        String signature = eventSignature(type, map);
        Instant now = clock.instant();
        synchronized (this) {
            Instant previous = recentEventSignatures.get(signature);
            recentEventSignatures.put(signature, now);
            if (previous != null && !now.isBefore(previous)
                    && now.minusSeconds(2).isBefore(previous)) return true;
            if (recentEventSignatures.size() > 512) recentEventSignatures.clear();
        }
        return false;
    }

    private static String eventSignature(String type, Map<String, String> map) {
        List<String> entries = new ArrayList<>();
        for (Map.Entry<String, String> entry : map.entrySet()) {
            entries.add(entry.getKey() + "=" + entry.getValue());
        }
        Collections.sort(entries);
        return type + "|" + entries;
    }

    private static int mapInt(Map<String, String> map, String key, int fallback) {
        try {
            String value = map.get(key);
            return value == null || value.isEmpty() ? fallback : Integer.parseInt(value);
        } catch (NumberFormatException ignored) {
            return fallback;
        }
    }

    static ChannelView toChannelView(Channel channel, ChannelView previous) {
        Codec codec = channel.getCodec();
        boolean voice = codec != Codec.UNKNOWN
                || (previous != null && previous.isVoiceCapable());
        String codecName = codec == Codec.UNKNOWN && previous != null
                ? previous.getCodec() : codec.name();
        return new ChannelView(channel.getId(), channel.getParentChannelId(), channel.getOrder(),
                channel.getName(), voice, codecName);
    }

