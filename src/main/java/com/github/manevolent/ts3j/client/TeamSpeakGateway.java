    public synchronized void connect(final ConnectionConfig connectionConfig) {
        if (closed) throw new IllegalStateException("gateway is closed");
        if (status == ConnectionStatus.CONNECTING
                || status == ConnectionStatus.CONNECTED_NO_CHANNEL
                || status == ConnectionStatus.CONNECTED_IN_CHANNEL) {
            return;
        }
        if (connectionConfig == null) throw new IllegalArgumentException("connectionConfig");
        config = connectionConfig;
        // Session starts are no longer persisted by each desktop instance.
        // The server-side ts3j-session-timer is authoritative; this in-memory
        // repository only carries the occupied-channel view used by JavaFX.
        sessions.useRepository(new InMemoryVoiceSessionRepository());
        // A persisted record cannot prove that the server stayed occupied
        // while this client was disconnected. Start this connection from the
        // server's next authoritative snapshot; a peer marker can restore a
        // known start when another client is already present.
        sessions.reconcile(connectionConfig.serverId(),
                Collections.<Integer, java.util.Collection<Integer>>emptyMap(), clock.instant(),
                gatewayEventId("connection-reset", Collections.<String, String>emptyMap()), 0L);
        status = ConnectionStatus.CONNECTING;
        errorMessage = "";
        chatHistoryWarning = "";
        permissionsLimited = false;
        nonUserClientIds.clear();
        pendingSessionMarkers.clear();
        pendingServerSessionMarkers.clear();
        latestServerSessionStarts.clear();
        pendingSessionMarkerRequests.clear();
        pendingSessionChannelRequests.clear();
        recentSessionMarkerSends.clear();
        recentSessionMarkerPeerRequests.clear();
        initialSync = true;
        sessionStateReady = false;
        channelMessages.clear();
        channelHistoryBoundaries.clear();
        loadChatHistory(connectionConfig.serverId());
        publish();

        final LocalTeamspeakClientSocket nextSocket = new LocalTeamspeakClientSocket();
        nextSocket.addListener(this);
        nextSocket.setNickname(connectionConfig.getNickname());
        nextSocket.setOption("client.meta_data", CLIENT_SESSION_METADATA);
        final TeamSpeakAudioBridge nextAudioBridge = audioDeviceService == null ? null
                : new TeamSpeakAudioBridge(audioDeviceService, this::currentVoiceCodec,
                        this::currentVoiceVolumeDb);
        if (nextAudioBridge != null) {
            nextAudioBridge.setMuted(false);
            audioDeviceService.clearCaptureFrames();
            nextSocket.setMicrophone(nextAudioBridge);
            nextSocket.setVoiceHandler(packet -> {
                TeamSpeakAudioBridge active = audioBridge;
                if (active == nextAudioBridge) active.handleVoicePacket(packet);
            });
        }
        audioBridge = nextAudioBridge;
        socket = nextSocket;

        ioExecutor.submit(new Runnable() {
            @Override
            public void run() {
                try {
                    nextSocket.setIdentity(loadIdentity());
                    nextSocket.connect(new InetSocketAddress(connectionConfig.getHost(),
                            connectionConfig.getPort()), connectionConfig.getPassword(), 15000L);
                    // onConnected schedules subscription/refresh on this same single
                    // executor after connect() returns, avoiding listener deadlock.
                } catch (Throwable error) {
                    synchronized (TeamSpeakGateway.this) {
                        status = ConnectionStatus.ERROR;
                        errorMessage = friendlyMessage(error);
                        sessionStateReady = false;
                        if (audioBridge == nextAudioBridge) {
                            if (audioBridge != null) audioBridge.close();
                            audioBridge = null;
                        }
                    }
                    publish();
                    closeSocket(nextSocket);
                }
            }
        });
    }

    public synchronized void disconnect() {
        final LocalTeamspeakClientSocket current = socket;
        if (current == null || status == ConnectionStatus.DISCONNECTED) return;
        ioExecutor.submit(new Runnable() {
            @Override
            public void run() {
                try {
                    current.disconnect();
                } catch (Throwable error) {
                    synchronized (TeamSpeakGateway.this) {
                        errorMessage = friendlyMessage(error);
                    }
                } finally {
                    closeSocket(current);
                    synchronized (TeamSpeakGateway.this) {
                        if (socket == current) {
                            socket = null;
                            status = ConnectionStatus.DISCONNECTED;
                            currentChannelId = -1;
                            clients.clear();
                            channels.clear();
                            channelMessages.clear();
                            channelHistoryBoundaries.clear();
                            chatHistoryWarning = "";
                            permissionsLimited = false;
                            pendingSessionMarkers.clear();
                            pendingServerSessionMarkers.clear();
                            latestServerSessionStarts.clear();
                            pendingSessionMarkerRequests.clear();
                            pendingSessionChannelRequests.clear();
                            recentSessionMarkerSends.clear();
                            recentSessionMarkerPeerRequests.clear();
                            if (audioBridge != null) audioBridge.close();
                            audioBridge = null;
                            initialSync = false;
                            sessionStateReady = true;
                        }
                    }
                    publish();
                }
            }
        });
    }

