    @Override
    public void close() {
        closed = true;
        disconnect();
        sessionMarkerRetryExecutor.shutdownNow();
        ioExecutor.shutdownNow();
        try {
            ioExecutor.awaitTermination(2, TimeUnit.SECONDS);
        } catch (InterruptedException interrupted) {
            Thread.currentThread().interrupt();
        }
    }
