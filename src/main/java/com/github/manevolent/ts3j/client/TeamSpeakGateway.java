    private void emitActivity(TeamSpeakActivity activity) {
        if (activity == null || activityListeners.isEmpty()) return;
        Instant now = clock.instant();
        synchronized (this) {
            // Each local send is a distinct user action even when several
            // messages share the same sender/channel signature. Other
            // protocol activities remain protected by the short duplicate
            // suppression window.
            if (activity.getType() != TeamSpeakActivity.Type.CHAT_SENT) {
                String signature = activity.signature();
                Instant previous = recentActivitySignatures.get(signature);
                recentActivitySignatures.put(signature, now);
                if (previous != null && !now.isBefore(previous)
                        && now.minusSeconds(2L).isBefore(previous)) return;
            }
            if (recentActivitySignatures.size() > 512) recentActivitySignatures.clear();
        }
        for (Consumer<TeamSpeakActivity> listener : activityListeners) {
            try {
                listener.accept(activity);
            } catch (RuntimeException ignored) {
                // A notification adapter must never break protocol processing.
            }
        }
    }

