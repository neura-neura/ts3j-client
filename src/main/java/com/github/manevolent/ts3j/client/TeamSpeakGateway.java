    static LocalIdentity loadOrCreateIdentity(Path identityPath)
            throws IOException, GeneralSecurityException {
        if (identityPath == null) throw new IllegalArgumentException("identityPath");
        Files.createDirectories(identityPath.getParent());
        boolean created = !Files.exists(identityPath);
        LocalIdentity identity = created
                ? LocalIdentity.generateNew(MINIMUM_IDENTITY_SECURITY)
                : LocalIdentity.read(identityPath.toFile());
        if (created || identity.getSecurityLevel() < MINIMUM_IDENTITY_SECURITY) {
            identity.improveSecurity(MINIMUM_IDENTITY_SECURITY);
            identity.save(identityPath.toFile());
        }
        return identity;
    }

    private static String friendlyMessage(Throwable error) {
        Throwable cause = error;
        while (cause.getCause() != null && (cause.getMessage() == null || cause.getMessage().isEmpty())) {
            cause = cause.getCause();
        }
        String message = cause.getMessage();
        if (message != null) {
            String normalized = message.toLowerCase(Locale.ROOT);
            if (normalized.contains("insufficient client permissions")) {
                return "El servidor aceptó la conexión, pero esta identidad no tiene permisos "
                        + "para consultar todos los canales. Usa la identidad oficial de TeamSpeak 3.";
            }
            if (normalized.contains("could not validate client identity")) {
                return "El servidor no pudo validar la identidad de TeamSpeak. "
                        + "Revisa la identidad oficial y vuelve a conectar.";
            }
            if (normalized.contains("timeout waiting for connected state")) {
                return "No hubo respuesta del servidor por UDP en el puerto 9987. "
                        + "El ping puede funcionar aunque UDP esté bloqueado: comprueba ZeroTier/VPN, "
                        + "el firewall y que TeamSpeak Server escuche en 9987/UDP. No requiere un certificado.";
            }
        }
        return message == null || message.isEmpty() ? cause.getClass().getSimpleName() : message;
    }

    private static boolean isInsufficientClientPermissions(Throwable error) {
        Throwable current = error;
        while (current != null) {
            String message = current.getMessage();
            if (message != null && message.toLowerCase(Locale.ROOT)
                    .contains("insufficient client permissions")) return true;
            current = current.getCause();
        }
        return false;
    }

