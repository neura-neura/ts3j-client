    @Override
    public void onDisconnected(DisconnectedEvent event) {
        int localId = localClientId();
        int channelId;
        String server = serverName();
        synchronized (this) {
            channelId = currentChannelId;
        }
        if (config != null && localId >= 0 && channelId >= 0) {
            sessions.leave(config.serverId(), channelId, localId, clock.instant(),
                    gatewayEventId("disconnect", Collections.<String, String>emptyMap()), 0L);
            clearSessionMarkerNegotiationAfterLeave(config.serverId(), channelId, localId);
        }
        synchronized (this) {
            status = ConnectionStatus.DISCONNECTED;
            currentChannelId = -1;
            clients.clear();
            nonUserClientIds.clear();
            channels.clear();
            channelMessages.clear();
            channelHistoryBoundaries.clear();
            chatHistoryWarning = "";
            permissionsLimited = false;
            pendingSessionMarkers.clear();
            pendingServerSessionMarkers.clear();
            latestServerSessionStarts.clear();
            pendingSessionMarkerRequests.clear();
            recentSessionMarkerSends.clear();
            recentSessionMarkerPeerRequests.clear();
            if (audioBridge != null) audioBridge.close();
            audioBridge = null;
            initialSync = false;
            sessionStateReady = true;
        }
        emitActivity(new TeamSpeakActivity(TeamSpeakActivity.Type.DISCONNECTED,
                "", "", "", server));
        publish();
    }

    private void refreshStatus() {
        synchronized (this) {
            if (status == ConnectionStatus.ERROR || status == ConnectionStatus.DISCONNECTED) {
                publish();
                return;
            }
            status = currentChannelId >= 0
                    ? ConnectionStatus.CONNECTED_IN_CHANNEL : ConnectionStatus.CONNECTED_NO_CHANNEL;
        }
        publish();
    }

